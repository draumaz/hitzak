function normalizeWord(word: string): string {
  return word
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, "")
    .trim();
}

function renderOptionText(text: string, buffer: string) {
  if (!buffer) return text;
  const cleanBuf = buffer.toLowerCase();
  const lowerText = text.toLowerCase();
  const idx = lowerText.indexOf(cleanBuf);
  if (idx === -1) return text;
  return (
    <span>
      {text.slice(0, idx)}
      <span className="text-[#1899d6] underline font-black">
        {text.slice(idx, idx + cleanBuf.length)}
      </span>
      {text.slice(idx + cleanBuf.length)}
    </span>
  );
}

